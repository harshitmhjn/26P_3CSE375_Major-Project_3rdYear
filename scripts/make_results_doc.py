"""Generate docs/RESULTS.md from results/experiments/*/summary*.csv (no typed-in numbers)."""
import glob
import os

import pandas as pd

import _bootstrap  # noqa: F401

COLS = [("hotspot_frequency", "Hotspot freq."), ("peak_temperature", "Peak T (C)"),
        ("it_energy_kwstep", "IT energy"), ("tasks_completed", "Completed"),
        ("tasks_dropped", "Dropped"), ("episode_return", "Return")]
out = ["# Results (generated by scripts/make_results_doc.py from results/experiments/)\n",
       "All numbers: mean over 5 held-out seeds (1001-1005); DRL rows are aggregated "
       "over 3 training seeds. Models were trained on the **steady** regime only, so "
       "diurnal/bursty are generalisation tests.\n"]
for d in sorted(glob.glob("results/experiments/*/")):
    name = os.path.basename(d.rstrip("/"))
    s = pd.read_csv(d + "summary.csv").set_index("policy")
    out.append(f"\n## Regime: {name}\n")
    out.append("| Policy | " + " | ".join(c[1] for c in COLS) + " |")
    out.append("|---|" + "---|" * len(COLS))
    for pol, row in s.iterrows():
        cells = [f"{row[c+'_mean']:.3f}" if c == "hotspot_frequency" else f"{row[c+'_mean']:.1f}" for c, _ in COLS]
        out.append(f"| {pol} | " + " | ".join(cells) + " |")
    pr = pd.read_csv(d + "summary_per_run.csv") if os.path.exists(d + "summary_per_run.csv") else None
    best = s.drop(index=[p for p in ("PPO", "DQN") if p in s.index]).hotspot_frequency_mean.idxmin()
    out.append(f"\nBest non-learning policy on hotspot frequency: **{best}** "
               f"({s.loc[best,'hotspot_frequency_mean']:.3f}).")
    for algo in ("PPO", "DQN"):
        if algo in s.index:
            r, b = s.loc[algo], s.loc[best]
            out.append(f"* {algo}: hotspot {r.hotspot_frequency_mean:.3f} vs {b.hotspot_frequency_mean:.3f}; "
                       f"completed {r.tasks_completed_mean:.0f} vs {b.tasks_completed_mean:.0f}; "
                       f"return {r.episode_return_mean:.0f} vs {b.episode_return_mean:.0f}.")
out.append("""
## Interpretation (read with the tables)

* **Neither DRL agent beats the best heuristic (greedy-coolest) on a fair basis.**
  PPO's hotspot rate is close to round-robin and its return is worse than both greedy heuristics.
* **DQN's low hotspot rate is not a win.** It completes far fewer tasks (it defers
  most of the work), so it avoids heat by not doing the work. Its episode return is
  also worse than greedy-coolest. Treat it as a degenerate/partial always-defer policy.
* Possible explanations (hypotheses, not tested here): limited training budget
  (300k steps); reward weights that make deferral attractive; sparse/delayed thermal
  credit assignment; no action masking during training; no hyper-parameter tuning;
  heuristics that read exact temperature are very strong in a deterministic-ish simulator.
* Training seeds vary noticeably (see summary_per_run.csv); conclusions rest on 3 seeds only.
""")
open("docs/RESULTS.md", "w").write("\n".join(out))
print("wrote docs/RESULTS.md")
